/**
 * Build-time lesson data: one record per lesson, with the bullet points
 * of its `<LessonSummary>`. Server-side only (content collection + raw
 * config). Consumers: `src/pages/recap/[locale].json.ts` (static JSON for
 * the Recap / ReviewToday prompts) and `<ProgressOverview>`.
 */
import { getCollection } from 'astro:content';
import { MODULES } from '../i18n/modules.mjs';

export interface LessonData {
  path: string; // '/it/<module>/<slug>/' (slug may be '<sub>/<slug>')
  title: string;
  livello: 'principiante' | 'intermedio' | 'avanzato';
  module: string; // module dir, e.g. 'fundamentals'
  summary: string[];
}

const configRaw = Object.values(
  import.meta.glob('/astro.config.mjs', {
    query: '?raw',
    import: 'default',
    eager: true,
  }),
)[0] as string | undefined;

// Manual sidebar lists in `astro.config.mjs` give the lesson order;
// autogenerated modules (fundamentals) fall back to `sidebar.order`.
const configOrder = new Map<string, number>();
if (configRaw) {
  const re = /slug:\s*'([a-z0-9-]+(?:\/[a-z0-9-]+)+)'/g;
  let m: RegExpExecArray | null;
  let i = 0;
  while ((m = re.exec(configRaw))) configOrder.set(m[1], i++);
}

/** Strip inline markdown / MDX tags down to plain text. */
function toPlainText(input: string): string {
  return input
    .replace(/<[^>]+>/g, '')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/(\*\*|__)(.+?)\1/g, '$2')
    .replace(/(^|[\s(])[*_]([^*_\n]+)[*_](?=[\s).,;:!?]|$)/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}

export function extractSummary(body: string): string[] {
  const match = body.match(/<LessonSummary[^>]*>([\s\S]*?)<\/LessonSummary>/);
  if (!match) return [];
  const bullets: string[] = [];
  for (const line of match[1].split(/\r?\n/)) {
    const item = line.match(/^\s*[-*]\s+(.*)$/);
    if (item) {
      bullets.push(item[1]);
    } else if (line.trim() && bullets.length > 0 && /^\s+/.test(line)) {
      bullets[bullets.length - 1] += ' ' + line.trim();
    }
  }
  return bullets.map(toPlainText).filter(Boolean);
}

export async function getLessonData(locale: 'it' | 'en'): Promise<LessonData[]> {
  const entries = await getCollection('docs');
  const moduleIndex = new Map(MODULES.map((m, i) => [m.dir, i]));
  const rows: Array<LessonData & { sort: [number, number, number, string] }> = [];

  for (const entry of entries) {
    const parts = entry.id.split('/');
    // `<locale>/<module>/<slug>`, or `<locale>/<module>/<sub>/<slug>` for
    // modules with nested folders (by-profession/<profession>/<slug>).
    if (parts.length < 3 || parts.length > 4 || parts[0] !== locale) continue;
    if (!entry.data.livello) continue;
    const mod = parts[1];
    const slug = parts.slice(2).join('/');
    const order = (entry.data.sidebar as { order?: number } | undefined)?.order;
    const cfg = configOrder.get(`${mod}/${slug}`);
    rows.push({
      path: `/${locale}/${mod}/${slug}/`,
      title: entry.data.title,
      livello: entry.data.livello,
      module: mod,
      summary: extractSummary(entry.body ?? ''),
      sort: [
        moduleIndex.get(mod) ?? 999,
        cfg ?? Number.POSITIVE_INFINITY,
        typeof order === 'number' ? order : Number.POSITIVE_INFINITY,
        slug,
      ],
    });
  }

  rows.sort((a, b) => {
    for (let i = 0; i < 3; i++) {
      if (a.sort[i] !== b.sort[i]) return a.sort[i] < b.sort[i] ? -1 : 1;
    }
    return a.sort[3].localeCompare(b.sort[3]);
  });
  return rows.map(({ sort, ...rest }) => rest);
}
