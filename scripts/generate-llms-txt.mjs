// scripts/generate-llms-txt.mjs
//
// Postbuild: emit dist/llms.txt, a curated index of the manual for LLM
// agents that fetch a site to understand its scope. Spec at
// https://llmstxt.org. The format is H1 title, blockquote summary,
// then H2 sections with bulleted links and short descriptions.
//
// English is the default locale of the site, so llms.txt is in English
// and points to /en/ URLs. The Italian mirror is mentioned at the bottom:
// every page mirrors the same path under /it/.
//
// The script reads MDX frontmatter from src/content/docs/en/, so any
// new lesson added under EN is picked up automatically on the next
// build, no manual upkeep of the index. Section order mirrors the
// sidebar in astro.config.mjs. Modules that exist as placeholders
// only (all `link: '#'`) are skipped: nothing to link to.

import fs from 'node:fs/promises';
import path from 'node:path';

const SITE = 'https://ai-guide.larosa.work';
const DOCS_DIR = path.join('src', 'content', 'docs', 'en');
const OUT = path.join('dist', 'llms.txt');

// Order and labels of the modules surfaced in llms.txt. Keep in sync
// with the sidebar in astro.config.mjs. Skip placeholder modules
// (for-students, for-teachers, going-deeper) until they have published
// lessons, since listing only "Soon" entries would be noise.
const MODULES = [
  { dir: null,             slug: 'start-here',  label: 'Start here' },
  { dir: 'fundamentals',   label: 'Fundamentals' },
  { dir: 'everyday-use',   label: 'Everyday use' },
  { dir: 'at-work',        label: 'At work' },
];

const REFERENCE = [
  { slug: 'glossary', label: 'Glossary' },
  { slug: 'about',    label: 'About' },
];

// Lightweight YAML frontmatter parser, scoped to the fields we read
// (title, description). Avoids pulling a dependency just for build.
function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const yaml = match[1];
  const data = {};
  for (const line of yaml.split(/\r?\n/)) {
    const m = line.match(/^([a-zA-Z_]+):\s*(.+)$/);
    if (!m) continue;
    const key = m[1];
    let val = m[2].trim();
    // Strip optional surrounding quotes (single or double). The MDX
    // files in this repo use unquoted strings for title/description,
    // but stay defensive for future entries.
    if ((val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    data[key] = val;
  }
  return data;
}

async function readLesson(filePath, urlPath) {
  const raw = await fs.readFile(filePath, 'utf8');
  const fm = parseFrontmatter(raw);
  if (!fm.title) return null;
  return {
    title: fm.title,
    description: fm.description ?? '',
    url: `${SITE}${urlPath}`,
  };
}

async function readModuleLessons(moduleDir) {
  // The order of lessons inside a module is the sidebar order in
  // astro.config.mjs for manually-listed modules (everyday-use, at-work),
  // and the frontmatter `sidebar.order` for autogenerated ones
  // (fundamentals). We don't have a programmatic source of truth here
  // without re-reading the Astro config, so we approximate: use
  // `sidebar.order` if present, otherwise fall back to alphabetical
  // (which is what `autogenerate` would produce). This matches the
  // current published order closely enough for an external index.
  const dir = path.join(DOCS_DIR, moduleDir);
  const files = (await fs.readdir(dir)).filter((f) => f.endsWith('.mdx'));
  const lessons = [];
  for (const file of files) {
    const slug = file.replace(/\.mdx$/, '');
    const full = path.join(dir, file);
    const raw = await fs.readFile(full, 'utf8');
    const fm = parseFrontmatter(raw);
    if (!fm.title) continue;
    // Pull sidebar.order if present (single-line YAML "order: N" nested
    // under sidebar). Cheap heuristic, since our parser is flat.
    const orderMatch = raw.match(/sidebar:[\s\S]*?order:\s*(\d+)/);
    const order = orderMatch ? Number(orderMatch[1]) : Number.POSITIVE_INFINITY;
    lessons.push({
      title: fm.title,
      description: fm.description ?? '',
      url: `${SITE}/en/${moduleDir}/${slug}/`,
      order,
      slug,
    });
  }
  lessons.sort((a, b) => {
    if (a.order !== b.order) return a.order - b.order;
    return a.slug.localeCompare(b.slug);
  });
  return lessons.map(({ order, slug, ...rest }) => rest);
}

function formatLesson({ title, description, url }) {
  return description
    ? `- [${title}](${url}): ${description}`
    : `- [${title}](${url})`;
}

async function main() {
  const lines = [];
  lines.push('# AI-Guide');
  lines.push('');
  lines.push(
    '> A free, bilingual (English and Italian) manual that teaches non-technical readers ' +
    'how to use conversational AI well, from the very first question through everyday ' +
    'productivity, work scenarios, and advanced topics. Audience: parents, teachers, ' +
    'professionals, students. Not engineers.'
  );
  lines.push('');
  lines.push(
    `The canonical site is ${SITE}. English is the default locale (\`/en/\`); ` +
    'every page is mirrored in Italian at the same path under `/it/`. URL slugs are ' +
    'identical across languages so any English URL below can be translated by ' +
    'replacing `/en/` with `/it/`.'
  );
  lines.push('');

  for (const mod of MODULES) {
    lines.push(`## ${mod.label}`);
    lines.push('');
    if (mod.dir === null) {
      // Top-level page (start-here.mdx) rather than a folder.
      const lesson = await readLesson(
        path.join(DOCS_DIR, `${mod.slug}.mdx`),
        `/en/${mod.slug}/`
      );
      if (lesson) lines.push(formatLesson(lesson));
    } else {
      const lessons = await readModuleLessons(mod.dir);
      for (const lesson of lessons) lines.push(formatLesson(lesson));
    }
    lines.push('');
  }

  lines.push('## Reference');
  lines.push('');
  for (const ref of REFERENCE) {
    const lesson = await readLesson(
      path.join(DOCS_DIR, `${ref.slug}.mdx`),
      `/en/${ref.slug}/`
    );
    if (lesson) lines.push(formatLesson(lesson));
  }
  lines.push('');

  lines.push('## Translations');
  lines.push('');
  lines.push(
    `The same manual is available in Italian at ${SITE}/it/. Every English page ` +
    'has an Italian counterpart at the same path; replace `/en/` with `/it/` in ' +
    'any URL above to get the Italian version.'
  );
  lines.push('');

  lines.push('## Optional');
  lines.push('');
  lines.push(`- [Sitemap](${SITE}/sitemap-index.xml): every public URL on the site.`);
  lines.push(`- [Privacy](${SITE}/en/privacy/): what is and is not collected about readers.`);
  lines.push('');

  await fs.writeFile(OUT, lines.join('\n'));
  console.log(`[llms-txt] wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
